    private javax.swing.JRadioButton rdoOn;
    private javax.swing.JTable tblRoles;
    private javax.swing.JTable tblUsers;
    private javax.swing.JTextField txtCreated_at;
    private javax.swing.JTextField txtEmail;
    private javax.swing.JTextField txtFullname;
    private javax.swing.JTextField txtPassword;
    private javax.swing.JTextField txtPhoneNumber;
    private javax.swing.JTextField txtUsername;
    // End of variables declaration//GEN-END:variables

    UserDAO dao = new UserDAOImpl();
    RoleDAO cdao = new RoleDAOImpl();

    List<Role> roles = List.of();
    List<User> items = List.of();

    private Timer createdAtTimer;

    @Override
    public void open() {
        this.setLocationRelativeTo(null);
        this.fillRoles();

        tblRoles.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                fillToTable();
            }
        });
        cboRoles.addActionListener(e -> fillToTable());

        this.fillToTable();
        this.clear();
    }

    @Override
    public void create() {
        if (!checkForm())
            return;

        try {
            dao.create(getForm());
            fillToTable();
            clear();
            XDialog.alert("Thêm mới người dùng thành công.");
        } catch (Exception e) {
            XDialog.alert("Lỗi khi thêm người dùng mới.");
        }
    }

    @Override
    public void update() {
        if (!checkForm())
            return;

        try {
            User d = getForm();
            dao.update(d);
            this.fillToTable();
            clear();
            XDialog.alert("Cập nhật thông tin người dùng thành công.");
        } catch (Exception e) {
            XDialog.alert("Lỗi khi cập nhật.");
        }
    }

    @Override
    public void delete() {
        if (XDialog.confirm("Bạn thực sự muốn xóa?")) {
            try {
                dao.deleteById(txtUsername.getText().trim());
                fillToTable();
                clear();
                XDialog.alert("Xóa người dùng thành công.");
            } catch (Exception e) {
                XDialog.alert("Lỗi khi xóa người dùng.");
            }
        }
    }

    @Override
    public void clear() {
        setForm(new User());
        cboRoles.setSelectedIndex(0);
        rdoOn.setSelected(true);
        setEditable(false);

        if (createdAtTimer == null) {
            createdAtTimer = new Timer(1000, e -> {
                txtCreated_at.setText(XDate.format(new Date(), "yyyy-MM-dd HH:mm"));
            });
        }

        createdAtTimer.start();
    }

    @Override
    public void setEditable(boolean editable) {
        btnCreate.setEnabled(!editable);
        btnUpdate.setEnabled(editable);
        btnDelete.setEnabled(editable);

        boolean hasRow = tblUsers.getRowCount() > 0;
        btnMoveFirst.setEnabled(editable && hasRow);
        btnMovePrevious.setEnabled(editable && hasRow);
        btnMoveNext.setEnabled(editable && hasRow);
        btnMoveLast.setEnabled(editable && hasRow);
    }

    private void setCheckedAll(boolean checked) {
        for (int i = 0; i < tblUsers.getRowCount(); i++) {
            tblUsers.setValueAt(checked, i, 5);
        }
    }

    @Override
    public void checkAll() {
        this.setCheckedAll(true);
    }

    @Override
    public void uncheckAll() {
        this.setCheckedAll(false);
    }

    @Override
    public void deleteCheckedItems() {
        if (XDialog.confirm("Bạn thực sự muốn xóa các mục chọn?")) {
            try {
                for (int i = 0; i < tblUsers.getRowCount(); i++) {
                    if (Boolean.TRUE.equals(tblUsers.getValueAt(i, 5))) {
                        dao.deleteById(items.get(i).getUsername());
                    }
                }
                fillToTable();
                XDialog.alert("Đã xóa thành công các mục chọn.");
            } catch (Exception e) {
                XDialog.alert("Lỗi khi xóa.");
            }
        }
    }

    @Override
    public void moveFirst() {
        this.moveTo(0);
    }

    @Override
    public void movePrevious() {
        this.moveTo(tblUsers.getSelectedRow() - 1);

    }

    @Override
    public void moveNext() {
        this.moveTo(tblUsers.getSelectedRow() + 1);
    }

    @Override
    public void moveLast() {
        this.moveTo(tblUsers.getRowCount() - 1);
    }

    @Override
    public void moveTo(int index) {
        if (index < 0) {
            this.moveLast();
        } else if (index >= tblUsers.getRowCount()) {
            this.moveFirst();
        } else {
            tblUsers.clearSelection();
            tblUsers.setRowSelectionInterval(index, index);
            this.edit();
        }
    }

    @Override
    public void edit() {
        int row = tblUsers.getSelectedRow();
        if (row >= 0) {
            setForm(items.get(row));
            setEditable(true);
            jTabbedPane1.setSelectedIndex(1);
        }
    }

    @Override
    public User getForm() {
        User u = new User();
        u.setUsername(txtUsername.getText());
        u.setPassword(txtPassword.getText());
        u.setFullname(txtFullname.getText());
        u.setEmail(txtEmail.getText());
        u.setPhoneNumber(txtPhoneNumber.getText());
        u.setCreated_at(XDate.parse(txtCreated_at.getText().trim(), "yyyy-MM-dd HH:mm"));

        Role r = (Role) cboRoles.getSelectedItem();
        u.setRoleId(r.getId());
        u.setStatus(rdoOn.isSelected());
        return u;
    }

    @Override
    public void setForm(User u) {
        if (createdAtTimer != null && createdAtTimer.isRunning()) {
            createdAtTimer.stop();
        }

        txtUsername.setText(u.getUsername());
        txtPassword.setText(u.getPassword());
        txtFullname.setText(u.getFullname());
        txtEmail.setText(u.getEmail());
        txtPhoneNumber.setText(u.getPhoneNumber());
        txtCreated_at.setText(XDate.format(u.getCreated_at(), "yyyy-MM-dd HH:mm"));
        for (int i = 0; i < cboRoles.getItemCount(); i++) {
            Object obj = cboRoles.getItemAt(i);
            if (obj instanceof Role) {
                Role r = (Role) obj;
                if (r.getId() == (u.getRoleId())) {
                    cboRoles.setSelectedIndex(i);
                    break;
                }
            }
        }
        if (u.isStatus()) {
            rdoOn.setSelected(true);
        } else {
            rdoOff.setSelected(true);
        }
    }

    @Override
    public void fillRoles() {
        DefaultComboBoxModel cboModel = (DefaultComboBoxModel) cboRoles.getModel();
        cboModel.removeAllElements();
        DefaultTableModel tblModel = (DefaultTableModel) tblRoles.getModel();
        tblModel.setRowCount(0);
        RoleDAO cdao = new RoleDAOImpl();
        roles = cdao.findAll();
        roles.forEach(role -> {
            cboModel.addElement(role);
            tblModel.addRow(new Object[] { role.getRoleName() });
        });
        tblRoles.setRowSelectionInterval(0, 0);
    }

    @Override
    public void fillToTable() {
        DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
        model.setRowCount(0);

        Integer roleId = null;

        int catRow = tblRoles.getSelectedRow();
        if (catRow >= 0 && catRow < roles.size()) {
            roleId = roles.get(catRow).getId();
        } else {
            Object obj = cboRoles.getSelectedItem();
            if (obj instanceof Role) {
                roleId = ((Role) obj).getId();
            }
        }

        if (roleId == null)
            return;

        items = dao.findByRoleId(roleId);
        for (User u : items) {
            model.addRow(new Object[] {
                    u.getUsername(),
                    u.getPassword(),
                    u.getFullname(),
                    u.getPhoneNumber(),
                    u.isStatus() ? "Hoạt động" : "Tạm ngừng",
                    false
            });
        }
        setEditable(false);
    }

    private boolean checkForm() {
        String username = txtUsername.getText().trim();
        String password = txtPassword.getText().trim();
        String fullname = txtFullname.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhoneNumber.getText().trim();

        if (username.isEmpty()) {
            XDialog.alert("Vui lòng nhập tên đăng nhập.");
            txtUsername.requestFocus();
            return false;
        }

        if (password.isEmpty()) {
            XDialog.alert("Vui lòng nhập mật khẩu.");
            txtPassword.requestFocus();
            return false;
        }

        if (fullname.isEmpty()) {
            XDialog.alert("Vui lòng nhập họ tên.");
            txtFullname.requestFocus();
            return false;
        }

        if (email.isEmpty()) {
            XDialog.alert("Vui lòng nhập email.");
            txtEmail.requestFocus();
            return false;
        }
        if (!email.matches("^[\\w.-]+@[\\w.-]+\\.[a-zA-Z]{2,}$")) {
            XDialog.alert("Email không hợp lệ.");
            txtEmail.requestFocus();
            return false;
        }

        if (phone.isEmpty()) {
            XDialog.alert("Vui lòng nhập số điện thoại.");
            txtPhoneNumber.requestFocus();
            return false;
        }
        if (!phone.matches("^\\d{10}$")) {
            XDialog.alert("Số điện thoại phải gồm 10 số.");
            txtPhoneNumber.requestFocus();
            return false;
        }

        return true;
    }
