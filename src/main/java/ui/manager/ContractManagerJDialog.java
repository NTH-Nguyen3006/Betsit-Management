@Override
public void fillToTable() {
    DefaultTableModel model = (DefaultTableModel) tblContractManager.getModel();
    model.setRowCount(0);

    try {
        items = dao.findAll();
        for (Contract item : items) {
            System.out.println(item.getId());
            System.out.println(item.getPaymentCycleMonths());
            Object[] rowData = {
                item.getId(),                    
                item.getRoomId(),              
                item.getTenant(),               
                item.getStartDate(),           
                item.getEndDate(),              
                item.getDepositAmount(),        
                item.getPaymentCycleMonths(), 
                item.getFile_scan_url(),
                item.getNotes()
            };
            model.addRow(rowData);
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Lỗi khi tải dữ liệu hợp đồng: " + e.getMessage());
        e.printStackTrace();
    }
}

@Override
    public void edit() {
        int row = tblContractManager.getSelectedRow();
        if (row >= 0 && row < items.size()) {
            Contract entity = items.get(row);
            setForm(entity);
            ContractDetail detail = contractDetailDAO.findById(entity.getId().toString());
            setDetailForm(detail);
            setEditable(true);
            tabs.setSelectedIndex(1);
        }
       
    }

