public void moveTo(int index) {
    if (index < 0) {
        this.moveLast();
    } else if (index >= tblContractManager.getRowCount()) {
        this.moveFirst();
    } else {
        tblContractManager.clearSelection();
        tblContractManager.setRowSelectionInterval(index, index);
        this.edit();
    }
}

