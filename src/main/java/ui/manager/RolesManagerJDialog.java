    @Override
    public void open() {
        this.setLocationRelativeTo(null);
        this.fillToTable();
        this.clear();
    }

    @Override
    public void fillToTable() {
        DefaultTableModel model = (DefaultTableModel) tblRoles.getModel();
        model.setRowCount(0);
        items = dao.findAll();
        items.forEach(item -> {
            Object[] rowData = {
                item.getId(),
                item.getRoleName(),
                item.getDescription(),
                false
            };
            model.addRow(rowData);
        });
    }

    @Override
    public void edit() {
        Role entity = items.get(tblRoles.getSelectedRow());
        this.setForm(entity);
        this.setEditable(true);
        tabs.setSelectedIndex(1);
    }

    @Override
    public void checkAll() {
        this.setCheckedAll(true);
    }

    @Override
    public void uncheckAll() {
        this.setCheckedAll(false);
    }

    private void setCheckedAll(boolean checked) {
        for (int i = 0; i < tblRoles.getRowCount(); i++) {
            tblRoles.setValueAt(checked, i, 3);
        }
    }

    @Override
    public void deleteCheckedItems() {
        int selectedCount = 0;
        for (int i = 0; i < tblRoles.getRowCount(); i++) {
            if (Boolean.TRUE.equals(tblRoles.getValueAt(i, 3))) {
                selectedCount++;
            }
        }

        if (selectedCount == 0) {
            XDialog.alert("Vui lòng chọn ít nhất một mục để xóa.");
            return;
        }

        if (XDialog.confirm("Bạn thực sự muốn xóa " + selectedCount + " mục đã chọn?")) {
            try {
                for (int i = 0; i < tblRoles.getRowCount(); i++) {
                    if (Boolean.TRUE.equals(tblRoles.getValueAt(i, 3))) {
                        dao.deleteById(items.get(i).getId());
                    }
                }
                this.fillToTable();
                XDialog.alert("Đã xóa thành công " + selectedCount + " mục.");
            } catch (Exception e) {
                XDialog.alert("Lỗi khi xóa.");
            }
        }
    }   

    @Override
    public void setForm(Role entity) {
        txtId.setText(String.valueOf(entity.getId()));
        txtRoleName.setText(entity.getRoleName());
        txtDescription.setText(entity.getDescription());
    }


    @Override
    public Role getForm() {
        return getForm(false); 
    }    
    public Role getForm(boolean isCreate) {
        Role entity = new Role();
        if (!isCreate && !txtId.getText().isEmpty()) {
            entity.setId(Integer.parseInt(txtId.getText()));
        }       
        entity.setRoleName(txtRoleName.getText());
        entity.setDescription(txtDescription.getText());
        return entity;
    }

    @Override
    public void create() {
        if (!checkForm()) return;
        
        try {
            Role entity = getForm(true);
            dao.create(entity);
            this.fillToTable();
            this.clear();
            XDialog.alert("Thêm mới thành công.");
        } catch (Exception e) {
            XDialog.alert("Lỗi khi thêm mới.");
        }
    }

    @Override
    public void update() {
        if (!checkForm()) return;
        
        try {
        Role entity = getForm(false);
        dao.update(entity);
        this.fillToTable();
        this.clear();
        XDialog.alert("Cập nhật thành công.");
        } catch (Exception e) {
            XDialog.alert("Lỗi khi cập nhật.");
        }
    }

    @Override
    public void delete() {
        if (XDialog.confirm("Bạn thực sự muốn xóa?")) {
            try {
                int id = Integer.parseInt(txtId.getText());
                dao.deleteById(id);
                this.fillToTable();
                this.clear();
                XDialog.alert("Xóa thành công.");
            } catch (Exception e) {
                XDialog.alert("Lỗi khi xóa.");
            }
        }
    }

    @Override
    public void clear() {
        setForm(new Role());
        txtId.setText("");
        this.setEditable(false);
    }

    @Override
    public void setEditable(boolean editable) {
        btnCreate.setEnabled(!editable);
        btnUpdate.setEnabled(editable);
        btnDelete.setEnabled(editable);
        int rowCount = tblRoles.getRowCount();
        btnMoveFirst.setEnabled(editable && rowCount > 0);
        btnMovePrevious.setEnabled(editable && rowCount > 0);
        btnMoveNext.setEnabled(editable && rowCount > 0);
        btnMoveLast.setEnabled(editable && rowCount > 0);
    }

    @Override
    public void moveFirst() {
        this.moveTo(0);
    }

    @Override
    public void movePrevious() {
        this.moveTo(tblRoles.getSelectedRow() - 1);
    }

    @Override
    public void moveNext() {
        this.moveTo(tblRoles.getSelectedRow() + 1);
    }

    @Override
    public void moveLast() {
        this.moveTo(tblRoles.getRowCount() - 1);
    }

    @Override
    public void moveTo(int index) {
        if (index < 0) {
            this.moveLast();
        } else if (index >= tblRoles.getRowCount()) {
            this.moveFirst();
        } else {
            tblRoles.clearSelection();
            tblRoles.setRowSelectionInterval(index, index);
            this.edit();
        }
    }
    
    private boolean checkForm() {
        String role = txtRoleName.getText().trim();

        if (role.isEmpty()) {
            XDialog.alert("Vui lòng nhập tên vai trò.");
            txtRoleName.requestFocus();
            return false;
        }
        if (btnCreate.isEnabled()) { 
            Role existingRole = dao.findByName(txtRoleName.getText().trim());
            if (existingRole != null) {
                XDialog.alert("Vai trò này đã tồn tại.");
                txtRoleName.requestFocus();
                return false;
            }
        }       
        return true;
    }
