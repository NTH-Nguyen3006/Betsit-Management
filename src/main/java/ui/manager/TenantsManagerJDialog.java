    /**
     * @param labelIcon      Đối tượng Icon từ Label truyền vào
     * @param filenameToSave Tên file sau khi lưu
     * 
     * @return <code>true</code> nếu lưu thành công, hoặc không có đối tượng để lưu
     *         và ngược lại.
     */
    private boolean saveCitizenCardImage(Icon labelIcon, String filenameToSave) {
        if (labelIcon == null)
            return true;

        ImageIcon imageIcon = (ImageIcon) labelIcon;
        Image image = imageIcon.getImage();
        File fileToWrite = new File("src/main/java/upload/images/cititzenCards", filenameToSave);

        BufferedImage bImage = new BufferedImage(
                image.getWidth(null), image.getHeight(null),
                BufferedImage.TYPE_INT_ARGB);
        bImage.getGraphics().drawImage(image, 0, 0, null);
        // FileInputStream fis = null;
        try {
            // fis = new FileInputStream(imageFile);
            // Files.write(f.toPath(), fis.readAllBytes());

            boolean success = ImageIO.write(bImage, "png", fileToWrite);
            if (success)
                return true;
            return false;

        } catch (IOException e) {
            e.printStackTrace();
            return false;
        }
    }

    private void loadImageToLblIcon(File imageFile, JLabel lblToUpload) {
        FileInputStream fis = null;
        try {
            fis = new FileInputStream(imageFile);
            ImageIcon icon = new ImageIcon(fis.readAllBytes());
            lblToUpload.setIcon(icon);
        } catch (IOException e) {
            e.printStackTrace();
        } finally {
            if (fis != null) {
                try {
                    fis.close();
                } catch (IOException e) {
                    e.printStackTrace();
                }
            }
        }
    }
    
    private void searchByCitizenId() {
        String citizenId = txtSearchCitizenId.getText().trim();
        if (citizenId.isEmpty()) {
            XDialog.alert("Vui lòng nhập số CCCD để tìm kiếm.");
            return;
        }

        Tenant tenant = dao.findById(citizenId);
        if (tenant == null) {
            XDialog.alert("Không tìm thấy cư dân với số CCCD: " + citizenId);
            return;
        }
        
        this.setForm(tenant);

        TenantDetail detail = detailDAO.findById(citizenId);
        if (detail != null) {
            this.setDetailForm(detail);
        } else {
            XDialog.alert("Không tìm thấy thông tin chi tiết cho cư dân này.");
        }

        this.setEditable(true);
        tabs.setSelectedIndex(1);
    }
    
    private boolean checkForm() {
        String citizenId = txtCitizen_id.getText().trim();
        String fullName = txtFullName.getText().trim();
        String dateOfBirth = txtDateOfBirth.getText().trim();
        String phoneNumber = txtPhoneNumber.getText().trim();
        String email = txtEmail.getText().trim();
        String vehiclePlate = txtVehiclePlate.getText().trim();
        String hometown = txtHometown.getText().trim();
        String occupation = txtOccupation.getText().trim();

        if (citizenId.isEmpty()) {
            XDialog.alert("Vui lòng nhập số CCCD.");
            txtCitizen_id.requestFocus();
            return false;
        }
        if (!citizenId.matches("\\d{12}")) {
            XDialog.alert("Số CCCD phải gồm 12 chữ số.");
            txtCitizen_id.requestFocus();
            return false;
        }

        if (fullName.isEmpty()) {
            XDialog.alert("Vui lòng nhập họ tên.");
            txtFullName.requestFocus();
            return false;
        }
        
        if (dateOfBirth.isEmpty()) {
            XDialog.alert("Vui lòng nhập ngày sinh.");
            txtDateOfBirth.requestFocus();
            return false;
        }
        if (XDate.parse(dateOfBirth) == null) {
            XDialog.alert("Ngày sinh không đúng định dạng dd/MM/yyyy.");
            txtDateOfBirth.requestFocus();
            return false;
        }

        if (phoneNumber.isEmpty()) {
            XDialog.alert("Vui lòng nhập số điện thoại.");
            txtPhoneNumber.requestFocus();
            return false;
        }
        if (!phoneNumber.matches("\\d{10}")) {
            XDialog.alert("Số điện thoại phải gồm 10 số.");
            txtPhoneNumber.requestFocus();
            return false;
        }

        if (!email.isEmpty() && !email.matches("^[\\w._%+-]+@[\\w.-]+\\.[a-zA-Z]{2,}$")) {
            XDialog.alert("Email không hợp lệ.");
            txtEmail.requestFocus();
            return false;
        }

        if (!vehiclePlate.isEmpty() && !vehiclePlate.matches("^[0-9]{2}[A-Z]\\d-\\d{3}\\.\\d{2}$")) {
            XDialog.alert("Biển số xe không đúng định dạng.");
            txtVehiclePlate.requestFocus();
            return false;
        }
        
        if (hometown.isEmpty()) {
            XDialog.alert("Vui lòng nhập quê quán.");
            txtHometown.requestFocus();
            return false;
        }
        
        if (occupation.isEmpty()) {
            XDialog.alert("Vui lòng nhập nghề nghiệp.");
            txtOccupation.requestFocus();
            return false;
        }

        return true;
    }
