    @Override
    public void create() {
        Tenant tenant = getForm();
        TenantDetail detail = getDetailForm();

        if (frontCardImage == null)
            detail.setPerCardFrontImage(null);
        if (backCardImage == null)
            detail.setPerCardBackImage(null);
        saveCitizenCardImage(frontCardImage, detail.getPerCardFrontImage());
        saveCitizenCardImage(backCardImage, detail.getPerCardBackImage());

        dao.create(tenant);
        detailDAO.create(detail);

        this.fillToTable();
        this.clear();
    }

    @Override
    public void update() {
        Tenant tenant = getForm();
        TenantDetail detail = getDetailForm();
        dao.update(tenant);
        detailDAO.update(detail);

        this.fillToTable();
    }

