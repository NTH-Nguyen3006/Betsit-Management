    private void saveCitizenCardImage(File imageFile, String filenameToSave) {
        if (imageFile == null)
            return;

        File f = new File("src/main/java/upload/images/cititzenCards", filenameToSave);
        System.out.println(f.getAbsolutePath());
        FileInputStream fis = null;
        try {
            fis = new FileInputStream(imageFile);
            Files.write(f.toPath(), fis.readAllBytes());
        } catch (IOException e) {
            e.printStackTrace();
        } finally {
            if (fis != null) {
                try {
                    fis.close();
                } catch (IOException e) {
                    e.printStackTrace();
                }
            }
        }
    }

    private void loadImageToLblIcon(File imageFile, JLabel lblToUpload) {
        FileInputStream fis = null;
        try {
            fis = new FileInputStream(imageFile);
            ImageIcon icon = new ImageIcon(fis.readAllBytes());
            lblToUpload.setIcon(icon);
        } catch (IOException e) {
            e.printStackTrace();
        } finally {
            if (fis != null) {
                try {
                    fis.close();
                } catch (IOException e) {
                    e.printStackTrace();
                }
            }
        }
    }
